// Helper functions for search, ranking, and aggregation
export const getTopPopulatedCountries = (limit = 10) => {
  return [...COUNTRIES_DATA]
    .sort((a, b) => b.population - a.population)
    .slice(0, limit);
};

export const getTopDensityCountries = (limit = 10) => {
  return [...COUNTRIES_DATA]
    .sort((a, b) => b.density - a.density)
    .slice(0, limit);
};

export const getFastestGrowingCountries = (limit = 10) => {
  return [...COUNTRIES_DATA]
    .sort((a, b) => b.growthRate - a.growthRate)
    .slice(0, limit);
};
